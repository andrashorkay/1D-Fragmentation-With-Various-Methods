#ifndef MATERIAL_FIELD_HH
#define MATERIAL_FIELD_HH

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

class StrengthFieldGenerator;

/**
 * @brief Material properties at a given physical position.
 */
struct MaterialPoint {
  double x;       /// Position along the bar [m].
  double sigma_c; /// Local cohesive strength [Pa].
  double G_c;     /// Fracture toughness [J/m^2].
};

/**
 * @brief One-dimensional spatial material field.
 *
 * The field stores the cohesive strength along the bar and a constant
 * fracture toughness. It can be generated once and subsequently loaded
 * by different numerical solvers to ensure that they use the same material.
 */
class MaterialField {
public:
  /**
   * @brief Generate a material field on a domain centred at x = 0.
   *
   * The generated field spans [-length/2, length/2]. The cohesive strength
   * is generated by the supplied strength-field generator, while the
   * fracture toughness is constant throughout the domain.
   *
   * @param length Total length of the one-dimensional domain [m].
   * @param n_points Number of points used to represent the field.
   * @param G_c Constant fracture toughness [J/m^2].
   * @param seed Seed used by the random-number generator.
   * @param strength_generator Generator used to produce sigma_c(x).
   *
   * @return Generated material field.
   */
  static MaterialField
  generate(double length,
           std::size_t n_points,
           double G_c,
           std::uint64_t seed,
           const StrengthFieldGenerator& strength_generator);

  /**
   * @brief Save the material field to a file.
   *
   * @param filename Path of the output file.
   */
  void save(const std::string& filename) const;

  /**
   * @brief Load a previously generated material field.
   *
   * @param filename Path of the material-field file.
   * @return Loaded material field.
   */
  static MaterialField load(const std::string& filename);

  /**
   * @brief Return the cohesive strength at position x.
   *
   * @param x Physical position along the bar [m].
   * @return Local cohesive strength [Pa].
   */
  double GetSigmac(double x) const;

  /**
   * @brief Return the fracture toughness at position x.
   *
   * @param x Physical position along the bar [m].
   * @return Fracture toughness [J/m^2].
   */
  double GetGc(double x) const;

private:
  /// Discrete representation of the material field.
  std::vector<MaterialPoint> points_;
};

#endif // MATERIAL_FIELD_HH